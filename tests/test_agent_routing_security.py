def test_retrieved_context_drops_live_transaction_values_even_from_legacy_vectors():
    class FakeRetriever:
        def retrieve(self, *args, **kwargs):
            return {
                "documents": [
                    "Return Policy: Unused products may be returned with a receipt.\n"
                    "Price: ₹9,999\n"
                    "Stock Quantity: 200\n"
                    "Availability: In Stock\n"
                    "Widget Alpha costs $99 and has 8 units in stock."
                ],
                "distances": [0.1],
                "metadatas": [{"business_id": "shop-a"}],
            }

    pipeline = RAGPipeline.__new__(RAGPipeline)
    pipeline.retriever = FakeRetriever()

    context = pipeline.retrieve_context("business_shop-a", "What is the return policy?")

    assert context == "Return Policy: Unused products may be returned with a receipt."
    assert "Price:" not in context
    assert "Stock Quantity:" not in context
    assert "Availability:" not in context
    assert "$99" not in context


def test_order_creation_requires_explicit_confirmation_and_validates_quantity(isolated_database):
    shop = BusinessManager().register_business(
        "Confirm Shop",
        "Electronics",
        username="confirm-shop",
    )
    product_id = _add_product(shop["business_id"], "Widget Alpha", price=1250)
    tools = AgentTools.__new__(AgentTools)

    not_confirmed = tools.create_order(
        shop["business_id"],
        "Customer",
        "9876543210",
        "Widget Alpha",
        payment_method="COD",
        product_id=product_id,
    )
    invalid_quantity = tools.create_order(
        shop["business_id"],
        "Customer",
        "9876543210",
        "Widget Alpha",
        quantity=True,
        payment_method="COD",
        product_id=product_id,
        confirmed=True,
    )

    assert not_confirmed == {
        "error": "Explicit customer confirmation is required before placing an order."
    }
    assert invalid_quantity == {"error": "Quantity must be a positive whole number."}
    assert _order_count(shop["business_id"]) == 0
    assert _get_product(product_id).stock_quantity == 5


