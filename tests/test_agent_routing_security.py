def _agent_with_real_sqlite_tools():
    agent = AIAgent.__new__(AIAgent)
    agent.memory = ConversationMemory()
    agent.tools = AgentTools.__new__(AgentTools)
    agent.llm = SimpleNamespace(
        generate_response=lambda messages, **kwargs: "Answer based on supplied evidence."
    )
    return agent


def _add_product(business_id, name, *, price, stock=5):
    session = get_session()
    try:
        product = Product(
            business_id=business_id,
            product_name=name,
            price=price,
            stock_quantity=stock,
            availability="In Stock" if stock else "Out of Stock",
            is_active=True,
        )
        session.add(product)
        session.commit()
        return product.id
    finally:
        session.close()


def test_live_price_query_uses_sqlite_not_conflicting_document_price(isolated_database):
    shop = BusinessManager().register_business(
        "Price Authority Shop",
        "Electronics",
        username="price-authority-shop",
    )
    product_id = _add_product(shop["business_id"], "Widget Alpha", price=1250)
    agent = _agent_with_real_sqlite_tools()
    rag_calls = []

    def conflicting_document_context(business_id, query):
        rag_calls.append((business_id, query))
        return "Widget Alpha costs ₹9,999. Stock Quantity: 200."

    agent.tools.get_business_context = conflicting_document_context

    response = agent.chat(shop["business_id"], "How much does Widget Alpha cost?")

    assert response["reply"] == "Widget Alpha is priced at ₹1,250."
    assert rag_calls == []
    assert _get_product(product_id).price == 1250


