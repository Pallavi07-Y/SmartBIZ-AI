def test_product_id_and_order_queries_cannot_cross_business_boundaries(isolated_database):
    manager = BusinessManager()
    shop_a = manager.register_business("Shop A", "Electronics", username="isolation-a")
    shop_b = manager.register_business("Shop B", "Electronics", username="isolation-b")
    product_a = _add_product(shop_a["business_id"], "Shared Phone", price=1500)
    product_b = _add_product(shop_b["business_id"], "Shared Phone", price=900)
    tools = AgentTools.__new__(AgentTools)

    live_a = tools.get_live_products(shop_a["business_id"], query="Shared Phone")
    cross_shop_order = tools.create_order(
        shop_a["business_id"],
        "Customer",
        "9876543210",
        "Shared Phone",
        payment_method="COD",
        product_id=product_b,
        confirmed=True,
    )

    own_order = tools.create_order(
        shop_b["business_id"],
        "Customer",
        "9876543210",
        "Shared Phone",
        payment_method="COD",
        product_id=product_b,
        confirmed=True,
    )

    assert len(live_a) == 1
    assert live_a[0]["business_id"] == shop_a["business_id"]
    assert live_a[0]["price"] == 1500
    assert cross_shop_order == {"error": "Product is no longer available in this shop."}
    assert tools.get_order_status(shop_a["business_id"], own_order["order_id"]) is None
    assert _get_product(product_a).stock_quantity == 5
    assert _get_product(product_b).stock_quantity == 4
    assert _order_count(shop_a["business_id"]) == 0
    assert _order_count(shop_b["business_id"]) == 1


